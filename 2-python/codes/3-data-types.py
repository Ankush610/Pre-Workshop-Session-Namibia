# Four basic types of data
laptops = 18           # int   - whole number
height = 1.75          # float - decimal number
animal = "zebra"       # str   - text
is_sunny = False       # bool  - True or False

print(type(laptops))

print(type(height))

print(type(animal))

print(type(is_sunny))

# Quotes make it text, even if it looks like a number
print(type("2026"))
