# Many values in one box
temperatures = [31, 28, 35, 30]

print(temperatures[0])     # 31 - first item (counting starts at 0)

print(temperatures[-1])    # 30 - last item

print(len(temperatures))   # 4  - how many items

temperatures.append(33)    # add to the end
print(temperatures)

print(sum(temperatures))   # add them all up
