# Python as a calculator
print(12 + 4)   # 16  add

print(20 - 7)   # 13  subtract

print(8 * 5)    # 40  multiply

print(15 / 4)   # 3.75 divide

print(15 // 4)  # 3   divide, keep whole number

print(15 % 4)   # 3   remainder

print(3 ** 2)   # 9   power

